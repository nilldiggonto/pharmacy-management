const SIM_BRANCH_CODES = ["BR-01", "BR-02", "BR-03", "BR-04", "BR-05", "BR-06", "BR-07"];

export function createSimulatedFlowEvent(): LiveFlowEvent {
  const roll = Math.random();
  const product = DEMO_PRODUCTS[Math.floor(Math.random() * DEMO_PRODUCTS.length)];
  const branch = SIM_BRANCH_CODES[Math.floor(Math.random() * SIM_BRANCH_CODES.length)];
  const id = `flow-${Date.now()}-${Math.floor(Math.random() * 999)}`;

  if (roll < 0.45) {
    const qty = 20 + Math.floor(Math.random() * 140);
    return {
      id,
      kind: "transfer",
      fromCode: "CW-01",
      toCode: branch,
      productName: product.name,
      quantity: qty,
      timestamp: nowIso(),
      note: `Live FEFO dispatch from CW-01 to ${branch}`,
    };
  }
  if (roll < 0.78) {
    const qty = 1 + Math.floor(Math.random() * 8);
    return {
      id,
      kind: "sale",
      fromCode: branch,
      toCode: "POS",
      productName: product.name,
      quantity: qty,
      timestamp: nowIso(),
      note: `POS checkout completed at ${branch}`,
    };
  }
  const qty = 100 + Math.floor(Math.random() * 350);
  return {
    id,
    kind: "receipt",
    fromCode: "SUP-SQR",
    toCode: "CW-01",
    productName: product.name,
    quantity: qty,
    timestamp: nowIso(),
    note: "Supplier goods receipt verified at CW-01",
  };
}

